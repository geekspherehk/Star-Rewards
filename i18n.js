let currentLanguage = 'zh';

function setLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    updateLanguageUI();
    // 礼物模板重渲染（模板文案随语言变）
    try { if (typeof renderGiftTemplateTabs === 'function') { renderGiftTemplateTabs(); renderGiftTemplateGrid(); } } catch (e) { console.warn('[gt] rerender on lang change', e); }
}

function getLanguage() {
    return localStorage.getItem('language') || 'zh';
}

function t(key, params) {
    const keys = key.split('.');
    let value = translations[currentLanguage];

    for (const k of keys) {
        if (value && value[k] !== undefined) {
            value = value[k];
        } else {
            return key;
        }
    }

    if (typeof value === 'string') {
        let result = value;
        if (params && typeof params === 'object') {
            Object.keys(params).forEach(p => {
                result = result.replace(new RegExp('\\{' + p + '\\}', 'g'), params[p]);
            });
        }
        return result;
    }

    // 数组 / 对象直接返回（如模板数据）
    return value;
}

function updateLanguageUI() {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        const translated = t(key);
        // 防御：翻译缺失时保留 HTML 中的默认文本，避免显示 key 名
        if (translated !== key) {
            element.textContent = translated;
        }
    });
    
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        const translated = t(key);
        if (translated !== key) {
            element.placeholder = translated;
        }
    });
}

function initLanguage() {
    currentLanguage = getLanguage();
    updateLanguageUI();
    
    const languageSelector = document.getElementById('language-selector');
    if (languageSelector) {
        languageSelector.value = currentLanguage;
    }
}